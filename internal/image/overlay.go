// OverlayConfig controls what metadata is rendered on captured images.
type OverlayConfig struct {
	Enabled  bool
	FontSize float64
	// ShowTimestamp renders the capture time.
	ShowTimestamp bool
	// ShowExposure renders exposure and gain info.
	ShowExposure bool
	// ShowTemperature renders the sensor temperature.
	ShowTemperature bool
	// ShowMean renders the mean brightness value.
	ShowMean bool
	// Extra text to display (e.g., location name).
	ExtraText string
}

// DefaultOverlayConfig returns a standard overlay configuration.
func DefaultOverlayConfig() OverlayConfig {
	return OverlayConfig{
		Enabled:         true,
		FontSize:        24,
		ShowTimestamp:   true,
		ShowExposure:    true,
		ShowTemperature: true,
		ShowMean:        false,
		ExtraText:       "",
	}
}

// ApplyOverlay renders metadata text onto the image.
// Uses a simple bitmap font approach to avoid external font dependencies.
func ApplyOverlay(img image.Image, meta camera.CaptureMeta, cfg OverlayConfig) image.Image {
	if !cfg.Enabled {
		return img
	}

	bounds := img.Bounds()
	canvas := image.NewRGBA(bounds)
	draw.Draw(canvas, bounds, img, bounds.Min, draw.Src)

	lines := buildOverlayLines(meta, cfg)
	if len(lines) == 0 {
		return canvas
	}

	// Draw a semi-transparent background bar at the bottom.
	lineHeight := int(cfg.FontSize * 1.4)
	barHeight := lineHeight*len(lines) + 10
	barRect := image.Rect(0, bounds.Max.Y-barHeight, bounds.Max.X, bounds.Max.Y)

	bgColor := color.RGBA{0, 0, 0, 160}
	draw.Draw(canvas, barRect, &image.Uniform{bgColor}, image.Point{}, draw.Over)

	// Render text lines using a simple approach.
	// For production use, replace with github.com/fogleman/gg for proper font rendering.
	textColor := color.RGBA{255, 255, 255, 255}
	y := bounds.Max.Y - barHeight + 8
	for _, line := range lines {
		drawSimpleText(canvas, 10, y, line, textColor)
		y += lineHeight
	}

	return canvas
}

func buildOverlayLines(meta camera.CaptureMeta, cfg OverlayConfig) []string {
	var lines []string

	if cfg.ShowTimestamp {
		lines = append(lines, meta.Timestamp.Format("2006-01-02 15:04:05 MST"))
	}

	if cfg.ShowExposure {
		expStr := formatExposure(meta.Exposure)
		lines = append(lines, fmt.Sprintf("Exp: %s  Gain: %.0f", expStr, meta.Gain))
	}

	if cfg.ShowTemperature && meta.Temperature != 0 {
		lines = append(lines, fmt.Sprintf("Sensor: %.1f°C", meta.Temperature))
	}

	if cfg.ShowMean && meta.MeanBrightness >= 0 {
		lines = append(lines, fmt.Sprintf("Mean: %.1f", meta.MeanBrightness))
	}

	if cfg.ExtraText != "" {
		lines = append(lines, cfg.ExtraText)
	}

	return lines
}

func formatExposure(d time.Duration) string {
	if d >= time.Second {
		return fmt.Sprintf("%.1fs", d.Seconds())
	}
	if d >= time.Millisecond {
		return fmt.Sprintf("%.1fms", float64(d.Microseconds())/1000.0)
	}
	return fmt.Sprintf("%dµs", d.Microseconds())
}

// drawSimpleText renders text using a basic pixel-based approach.
// Each character is 6x10 pixels. This is intentionally simple.
// For nicer text, use fogleman/gg with a TTF font.
func drawSimpleText(img *image.RGBA, x, y int, text string, col color.RGBA) {
	// Simple 5x7 bitmap font for ASCII 32-126.
	for i, ch := range text {
		if ch < 32 || ch > 126 {
			ch = '?'
		}
		cx := x + i*7
		drawChar(img, cx, y, byte(ch), col)
	}
}

// drawChar draws a single character using a minimal bitmap font.
func drawChar(img *image.RGBA, x, y int, ch byte, col color.RGBA) {
	glyph := getGlyph(ch)
	for row := 0; row < 7; row++ {
		for col_bit := 0; col_bit < 5; col_bit++ {
			if glyph[row]&(1<<(4-col_bit)) != 0 {
				px := x + col_bit
				py := y + row
				if px >= 0 && px < img.Bounds().Max.X && py >= 0 && py < img.Bounds().Max.Y {
					img.SetRGBA(px, py, col)
				}
			}
		}
	}
}

// getGlyph returns a 5x7 bitmap for common characters used in the overlay.
func getGlyph(ch byte) [7]byte {
	// Minimal font for digits, letters, and common punctuation.
	switch {
	case ch >= '0' && ch <= '9':
		return digitGlyphs[ch-'0']
	case ch >= 'A' && ch <= 'Z':
		return upperGlyphs[ch-'A']
	case ch >= 'a' && ch <= 'z':
		return lowerGlyphs[ch-'a']
	case ch == ' ':
		return [7]byte{0, 0, 0, 0, 0, 0, 0}
	case ch == ':':
		return [7]byte{0x00, 0x04, 0x00, 0x00, 0x04, 0x00, 0x00}
	case ch == '.':
		return [7]byte{0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x00}
	case ch == '-':
		return [7]byte{0x00, 0x00, 0x00, 0x0E, 0x00, 0x00, 0x00}
	case ch == '/':
		return [7]byte{0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10}
	default:
		return [7]byte{0x0A, 0x00, 0x0A, 0x00, 0x0A, 0x00, 0x0A} // checkerboard for unknown
	}
}

